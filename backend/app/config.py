from functools import lru_cache
from typing import Literal

from pydantic import SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Application settings loaded from environment variables."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    APP_TITLE: str = "Hisaab API"
    APP_VERSION: str = "1.0.0"
    ENVIRONMENT: Literal["dev", "staging", "prod"] = "dev"
    LOG_LEVEL: str = "INFO"

    DATABASE_URL: str = "sqlite+aiosqlite:///./hisaab_dev.db"
    SECRET_KEY: SecretStr = SecretStr("dev-secret-key-change-me-32-bytes!!")

    GOOGLE_CLIENT_ID: str = ""
    GOOGLE_CLIENT_SECRET: SecretStr = SecretStr("")
    GOOGLE_REDIRECT_URI: str = "http://localhost:8000/api/v1/auth/google/callback"

    GROQ_API_KEY: SecretStr = SecretStr("")
    GEMINI_API_KEY: SecretStr = SecretStr("")
    MISTRAL_API_KEY: SecretStr = SecretStr("")

    LLM_PROVIDERS: list[str] = [
        "groq:openai/gpt-oss-120b",
        "groq:openai/gpt-oss-20b",
        "gemini:gemini-3.5-flash-lite",
        "mistral:ministral-8b-latest",
    ]
    LLM_MAX_CONCURRENT: int = 3
    LLM_CACHE_TTL_SECONDS: int = 86400
    LLM_TIMEOUT_SECONDS: int = 30

    ESCALATION_THRESHOLDS_DAYS: list[int] = [7, 21, 45]
    NOT_LEGAL_ADVICE_TEXT: str = (
        "This draft is generated by AI for reference only. It does not constitute legal advice. "
        "Please consult a qualified legal professional for advice specific to your situation."
    )

    RATE_LIMIT_DEFAULT: str = "60/minute"
    CORS_ORIGINS: list[str] = ["http://localhost:5173"]

    SESSION_COOKIE_NAME: str = "session_id"
    SESSION_COOKIE_SECURE: bool = False
    SESSION_TTL_SECONDS: int = 7 * 24 * 3600
    CSRF_COOKIE_NAME: str = "csrf_token"


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
